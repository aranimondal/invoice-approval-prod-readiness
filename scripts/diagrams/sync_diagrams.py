#!/usr/bin/env python3
"""Keeps every architecture diagram in one place: the .mmd file.

The .mmd files in docs/architecture are the source of truth (diagram-as-code). This script:
  * regenerates docs/architecture/README.md with, for every diagram, the rendered SVG,
    the full Mermaid source as copy-pasteable text, and an "Open in Mermaid Live" link;
  * rewrites the ```mermaid blocks inside as-built.md / target-state.md from the .mmd files,
    each followed by a collapsible copy of the source and the same live-editor link.

Usage:
    python3 scripts/diagrams/sync_diagrams.py          # rewrite the docs
    python3 scripts/diagrams/sync_diagrams.py --check  # CI: fail if docs drifted from .mmd

SVGs are rendered separately with mermaid-cli (see docs/architecture/README.md).
Standard library only.
"""
import base64
import json
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ARCH = ROOT / "docs" / "architecture"

DIAGRAMS = [
    # (file stem, title, explaining doc, anchor, one-line caption)
    ("as-built-container", "As-built: container view", "as-built.md", "container-view",
     "What runs today: one JVM, two Maven modules. The domain module has no framework in it."),
    ("as-built-approval-sequence", "As-built: approval sequence", "as-built.md", "sequence-approving-an-invoice",
     "Step 9: `findById` returns the live object. That is the root of the double-approve race."),
    ("target-container", "Target: container view", "target-state.md", "container-view",
     "Persistence, the transactional outbox and PayEx. Dashed orange = not built yet. Service Bus is provisioned and deliberately unused in v1."),
    ("target-approval-sequence", "Target: approval and payment sequence", "target-state.md", "approval-and-payment-sequence",
     "PayEx is off the approver's request path. A timeout becomes `Unknown`, and we look the payment up before ever re-sending."),
]

BLOCK = re.compile(r"```mermaid\n(.*?)```\n(?:\n<details><summary>Mermaid source.*?</details>\n)?", re.S)


def diagram_code(stem):
    text = (ARCH / f"{stem}.mmd").read_text(encoding="utf-8")
    return "\n".join(line for line in text.splitlines() if not line.startswith("%%")).strip() + "\n"


def live_link(code):
    """Same encoding the Mermaid Live Editor uses for its own share links (pako = zlib + base64url)."""
    state = {"code": code, "mermaid": json.dumps({"theme": "default"}), "autoSync": True, "updateDiagram": True}
    packed = zlib.compress(json.dumps(state).encode("utf-8"), 9)
    return "https://mermaid.live/edit#pako:" + base64.urlsafe_b64encode(packed).decode("ascii")


def source_details(stem, code):
    return (f"\n<details><summary>Mermaid source of this diagram (from <code>{stem}.mmd</code>), "
            f"to paste into mermaid.live</summary>\n\n```text\n{code}```\n\n"
            f"[Open this diagram in the Mermaid Live Editor]({live_link(code)})\n\n</details>\n")


def render_readme():
    out = [
        "# Diagrams",
        "",
        "<!-- Generated by scripts/diagrams/sync_diagrams.py from the .mmd files. Edit the .mmd, not this page. -->",
        "",
        "Every diagram here is **diagram-as-code**: it's written as Mermaid text in a `.mmd` file in this folder, and the picture is generated from that text. Nothing is drawn by hand. That means a diagram change is a text diff that gets reviewed in a PR like any other code.",
        "",
        "For each diagram below you'll find:",
        "",
        "1. **The picture** (an SVG generated from the source with mermaid-cli).",
        "2. **The exact Mermaid source.** Copy it into [mermaid.live](https://mermaid.live) or any Mermaid renderer to reproduce the picture.",
        "3. **A one-click link** that opens the same source in the Mermaid Live Editor.",
        "",
        "The same diagrams also render live inside the documents that explain them, where every box carries a citation to the code.",
        "",
        "| Diagram | Source file | Explained in |",
        "| --- | --- | --- |",
    ]
    for stem, title, doc, anchor, _ in DIAGRAMS:
        out.append(f"| {title} | [`{stem}.mmd`]({stem}.mmd) | [{doc}]({doc}#{anchor}) |")
    out.append("")
    for stem, title, doc, anchor, caption in DIAGRAMS:
        code = diagram_code(stem)
        out += [
            f"## {title}",
            "",
            caption,
            "",
            f"![{title}](img/{stem}.svg)",
            "",
            f"**Mermaid source** ([`{stem}.mmd`]({stem}.mmd)):",
            "",
            "```text",
            code.rstrip("\n"),
            "```",
            "",
            f"[Open in the Mermaid Live Editor]({live_link(code)})",
            "",
        ]
    out += [
        "## How the pictures are generated",
        "",
        "```bash",
        "# 1. Edit a .mmd file. Then regenerate its SVG (Node 18+):",
        "npx -y @mermaid-js/mermaid-cli -i docs/architecture/as-built-container.mmd -o docs/architecture/img/as-built-container.svg -b white",
        "",
        "# 2. Push the same source into this page and into as-built.md / target-state.md:",
        "python3 scripts/diagrams/sync_diagrams.py",
        "```",
        "",
        "CI runs `sync_diagrams.py --check`, so a PR fails if a document shows a diagram that differs from its `.mmd` source.",
        "",
    ]
    return "\n".join(out)


def sync_doc(doc_name, stems):
    path = ARCH / doc_name
    text = path.read_text(encoding="utf-8")
    blocks = list(BLOCK.finditer(text))
    if len(blocks) != len(stems):
        raise SystemExit(f"{doc_name}: expected {len(stems)} mermaid blocks, found {len(blocks)}")
    pieces, last = [], 0
    for match, stem in zip(blocks, stems):
        code = diagram_code(stem)
        pieces.append(text[last:match.start()])
        pieces.append(f"```mermaid\n{code}```\n" + source_details(stem, code))
        last = match.end()
    pieces.append(text[last:])
    return path, "".join(pieces)


def main():
    check = "--check" in sys.argv
    targets = [(ARCH / "README.md", render_readme())]
    targets.append(sync_doc("as-built.md", ["as-built-container", "as-built-approval-sequence"]))
    targets.append(sync_doc("target-state.md", ["target-container", "target-approval-sequence"]))

    drift = []
    for path, wanted in targets:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != wanted:
            drift.append(path.relative_to(ROOT))
            if not check:
                path.write_text(wanted, encoding="utf-8")

    for stem, *_ in DIAGRAMS:
        if not (ARCH / "img" / f"{stem}.svg").exists():
            drift.append(f"docs/architecture/img/{stem}.svg (missing)")

    if check and drift:
        print("Diagrams out of sync with their .mmd sources:", *drift, sep="\n  ")
        print("Run: python3 scripts/diagrams/sync_diagrams.py")
        sys.exit(1)
    print("updated: " + ", ".join(map(str, drift)) if drift and not check else "diagrams in sync")


if __name__ == "__main__":
    main()
